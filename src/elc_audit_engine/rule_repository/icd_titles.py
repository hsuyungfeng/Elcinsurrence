def get_icd_chinese_title(code: str | None) -> str | None:
    """查詢 ICD-10 診斷碼的標準中文名稱。

    - 支援格式如 'S6702XA' 或 'S67.02XA'
    - 精確比對優先；若無，嘗試前綴降級匹配（如 S67.02 -> S67.0）
    - 查無資料時傳回 None。
    """
    if not code:
        return None
    raw = str(code).strip()
    norm = re.sub(r"[^A-Za-z0-9]", "", raw).upper()
    if not norm:
        return None

    # 1. 完全比對
    if norm in _ICD10_CHINESE:
        return _ICD10_CHINESE[norm]

    # 2. 逐級前綴回退（針對末尾 encounter code 如 XA/XD/XS）
    for length in (7, 6, 5, 4, 3):
        if len(norm) > length:
            sub = norm[:length]
            if sub in _ICD10_CHINESE:
                return _ICD10_CHINESE[sub]

    return None
